"""Настройки автоответчика: токен, пути, заводские значения.

Всё, что владелец правит на ходу — тексты, правила, паузы — лежит в
SQLite и меняется кнопками в личке бота. Здесь только то, что задаётся
один раз при установке, плюс значения по умолчанию для нового
подключения.

Отдельно про осторожные заводские настройки: бот пишет от имени
живого человека в его личные чаты. Поэтому сразу после подключения он
молчит — ни приветствий, ни ответов «по умолчанию». Пока владелец не
добавил правила, отправлять от его имени попросту нечего.
"""

from __future__ import annotations

import os
from pathlib import Path

from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent
#: Хостинги отдают под данные отдельный том и сообщают о нём переменной
#: DATA_DIR. Не слушать её нельзя: база ляжет рядом с кодом и сотрётся
#: на первом же передеплое вместе с правилами и текстами.
DATA_DIR = Path(os.getenv("DATA_DIR") or BASE_DIR / "data")
DATA_DIR.mkdir(parents=True, exist_ok=True)

load_dotenv(BASE_DIR / ".env")


def _ints(raw: str | None) -> set[int]:
    if not raw:
        return set()
    out: set[int] = set()
    for chunk in raw.replace(";", ",").split(","):
        chunk = chunk.strip()
        if chunk.lstrip("-").isdigit():
            out.add(int(chunk))
    return out


#: Имя проекта. Стоит во всех заголовках панели и в справке — меняется
#: здесь одной строкой, переименование ничего больше не задевает.
#: Telegram называет эту роль «режимом секретаря», а дублёр — тот, кто
#: выходит на площадку вместо тебя и его не отличают от тебя.
BRAND = os.getenv("BRAND", "Дублёр")

BOT_TOKEN = os.getenv("BOT_TOKEN", "").strip()

#: Кому разрешено подключать бота к своему Telegram Business. Пусто —
#: разрешено всем, кто нашёл бота: у каждого владельца свои правила и
#: своя статистика, они не пересекаются. Для личного автоответчика
#: впиши сюда свой id — иначе чужие люди смогут гонять твой сервер.
ALLOWED_IDS = _ints(os.getenv("ALLOWED_IDS"))

DB_PATH = Path(os.getenv("DB_PATH", DATA_DIR / "autochat.db"))

# --------------------------------------------------------------------------
# Заводские значения для нового подключения
# --------------------------------------------------------------------------

#: Пауза между автоответами в одном чате, секунды. Без неё бот отвечает
#: на каждое сообщение подряд — человек пишет три строки в три
#: сообщения и получает три одинаковых ответа.
#:
#: Правило, отличное от прошлого, паузу игнорирует: если собеседник
#: сначала спросил про цену, а через минуту про сроки, ответить нужно
#: на оба вопроса, а не молчать до конца кулдауна.
COOLDOWN = int(os.getenv("COOLDOWN", "120"))

#: Сколько минут молчать в чате после того, как владелец написал туда
#: сам. Главное правило вежливости автоответчика: если человек уже
#: разговаривает, бот не должен вклиниваться в диалог со своими
#: заготовками. 0 — отключить эту паузу.
PAUSE_MINUTES = int(os.getenv("PAUSE_MINUTES", "30"))

#: Задержка перед ответом, секунды (от и до, берётся случайно). Мгновенный
#: ответ в личке выдаёт робота сильнее любого текста, поэтому бот сначала
#: показывает «печатает…», а потом отправляет.
DELAY_MIN = float(os.getenv("DELAY_MIN", "1.5"))
DELAY_MAX = float(os.getenv("DELAY_MAX", "3.5"))

# --------------------------------------------------------------------------
# Архив сообщений: «увидеть удалённое»
# --------------------------------------------------------------------------

#: Ловить ли удалённые сообщения. Telegram присылает боту апдейт об
#: удалении, но в нём только номера сообщений — ни текста, ни автора.
#: Поэтому единственный способ показать удалённое: складывать входящие
#: в свою базу при получении и доставать оттуда, когда их удалят.
#: Всё, что пришло до подключения бота, для него не существует.
SPY = os.getenv("SPY", "1").strip() not in ("0", "", "off", "no")

#: Сообщать ли о правках чужих сообщений: было → стало. Работает из
#: того же архива и по тем же ограничениям.
SPY_EDITS = os.getenv("SPY_EDITS", "1").strip() not in ("0", "", "off", "no")

#: Сколько дней держать архив входящих. Удалить успевают в первые
#: минуты, так что трёх дней хватает с запасом, а база не пухнет.
KEEP_DAYS = int(os.getenv("KEEP_DAYS", "3"))

#: Сколько символов сообщения сохранять. Длинные тексты в личке редки,
#: а место архив занимает на каждом сообщении.
ARCHIVE_TEXT_LEN = int(os.getenv("ARCHIVE_TEXT_LEN", "2000"))

#: Как часто подчищать архив и журнал, секунды.
CLEANUP_INTERVAL = int(os.getenv("CLEANUP_INTERVAL", "3600"))

# --------------------------------------------------------------------------
# Ограничители
# --------------------------------------------------------------------------

#: Ограничители, чтобы кнопочная админка не превратилась в способ
#: положить бота: правил много не нужно, а текст ответа длиннее этого
#: Telegram всё равно не пропустит одним сообщением.
MAX_RULES = int(os.getenv("MAX_RULES", "60"))
MAX_TEXT_LEN = int(os.getenv("MAX_TEXT_LEN", "900"))
MAX_TRIGGERS = int(os.getenv("MAX_TRIGGERS", "20"))

#: Сколько дней держать журнал автоответов. Он нужен для статистики и
#: разбора «почему бот это написал», но расти вечно ему незачем.
LOG_KEEP_DAYS = int(os.getenv("LOG_KEEP_DAYS", "30"))

#: Сколько чатов показывать в разделе «Чаты».
CHATS_PAGE = int(os.getenv("CHATS_PAGE", "12"))

DEFAULT_GREET = (
    "Привет, {name}! Сейчас не у телефона — прочитаю и отвечу, "
    "как только вернусь."
)
DEFAULT_AWAY = (
    "Я отошёл и вернусь позже. Сообщение вижу — отвечу, как только смогу."
)
DEFAULT_FALLBACK = "Понял, отвечу чуть позже."

#: Примеры правил для кнопки «добавить примеры» в пустом списке. Тексты
#: намеренно общие: их положено переписать под себя, и об этом бот
#: пишет прямым текстом сразу после добавления.
SAMPLE_RULES: tuple[tuple[str, str], ...] = (
    ("привет|прив|здравствуйте|добрый день", "Привет, {name}! Слушаю."),
    ("цена|сколько стоит|прайс|стоимость", "Цены скину, как освобожусь."),
    ("ты тут|ты там|на месте|алло", "На месте, читаю. Отвечу через пару минут."),
)


def check() -> None:
    """Ранняя проверка: без токена стартовать бессмысленно."""
    if not BOT_TOKEN:
        raise SystemExit(
            "Не задан BOT_TOKEN. Скопируй .env.example в .env и впиши токен "
            "от @BotFather."
        )
